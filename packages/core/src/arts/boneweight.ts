export interface BoneWeightResult {
  totalLiang: number;          // 总骨重（两）
  label: string;               // "4两4钱"
  parts: Array<{ name: string; value: string }>;
  poem: string;
  plain: string;
}

function liangText(liang: number): string {
  const l = Math.floor(liang);
  const q = Math.round((liang - l) * 10);
  return q === 0 ? `${l}两` : `${l}两${q}钱`;
}

/** 由公历输入计算称骨（自动转农历）。hourMissing 时按 0 点（子时）计并要求显式标注。 */
export function computeBoneWeight(y: number, m: number, d: number, hour: number, minute: number): BoneWeightResult {
  const solar = Solar.fromYmdHms(y, m, d, Math.min(23, Math.max(0, hour)), minute, 0);
  const lunar: any = solar.getLunar();
  // 年干支（考虑立春换年：称骨多用农历年，这里以 lunar 农历年干支）
  const yearGz = lunar.getYearInGanZhi();
  // 农历月：闰月按同月处理（lunar.getMonth() 负数=闰月，取绝对值）
  let lunarMonth = Math.abs(lunar.getMonth()); // 1..12
  if (lunarMonth === 0) lunarMonth = 1;
  const lunarDay = Math.abs(lunar.getDay());   // 1..30
  // 时辰地支（钟表）——称骨以当地时辰为准
  const zhiIdx = Math.floor((hour + 1) / 2) % 12;
  const yearV = YEAR_BONE[yearGz] ?? 0;
  const monthV = MONTH_BONE[lunarMonth - 1] ?? 0;
  const dayV = DAY_BONE[lunarDay - 1] ?? 0;
  const hourV = HOUR_BONE[zhiIdx] ?? 0;
  const total = Math.round((yearV + monthV + dayV + hourV) * 10) / 10;
  const key = total.toFixed(1);
  const song = BONE_SONG[key] ?? { poem: '骨重超出常见范围', plain: '此骨重较罕见，供参考。' };
  const zhis = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥'];
  return {
    totalLiang: total,
    label: liangText(total),
    parts: [
      { name: `年（${yearGz}）`, value: liangText(yearV) },
      { name: `月（农历${lunarMonthCn(lunarMonth)}）`, value: liangText(monthV) },
      { name: `日（农历${toCnDay(lunarDay)}）`, value: liangText(dayV) },
      { name: `时（${zhis[zhiIdx]}时）`, value: liangText(hourV) },
    ],
    poem: song.poem,
    plain: song.plain,
  };
}

function toCnDay(n: number): string {
  const tens = ['', '十', '廿', '三十'];
  const ones = ['', '一', '二', '三', '四', '五', '六', '七', '八', '九'];
  if (n <= 10) return ones[n - 1];
  if (n < 20) return '十' + (n === 10 ? '' : ones[n - 10]);
  if (n < 30) return '廿' + (n === 20 ? '' : ones[n - 20]);
  return '三十' + (n === 30 ? '' : ones[n - 30]);
}

/** 农历月份中文名（用于展示） */
export function lunarMonthCn(m: number): string {
  return ['', '正', '二', '三', '四', '五', '六', '七', '八', '九', '十', '冬', '腊'][m] + '月';
}