/** 每日一签：按当天日期（YYYY-M-D）哈希取稳定签文 */
export function dailySign(d = new Date()): Sign {
  const key = `${d.getFullYear()}-${d.getMonth() + 1}-${d.getDate()}`;
  let h = 0;
  for (const c of key) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return SIGNS[h % SIGNS.length];
}

