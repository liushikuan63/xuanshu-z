/** 断语“一句人话”：把前几条断语套成一句话结论 */
export function oneLineHuman(artName: string, rules: RuleLite[]): { emoji: string; line: string } {
  const top = rules.slice(0, 3);
  const ji = rules.filter((r) => r.level === '吉').length;
  const xiong = rules.filter((r) => r.level === '凶').length;
  const trend = ji > xiong ? '偏顺' : xiong > ji ? '偏阻' : '有反复';
  let line = `你问的这件事，整体${trend}。`;
  if (top[0]) line += `最关键的一条是「${top[0].title}」：${(top[0].fact ?? '').replace(/[。；]$/, '')}。`;
  if (top[1]) line += `其次留意「${top[1].title}」。`;
  if (!top[0] && !top[1]) line += '本轮暂无明显强信号，建议换个问法或换个术数再看。';
  return { emoji: ji > xiong ? '🌤' : xiong > ji ? '⛈' : '🌫', line };
}